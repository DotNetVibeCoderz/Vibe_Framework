using System.Text;
using JSNet.Semantics;
using JSNet.Syntax;

namespace JSNet.CodeGen;

/// <summary>Per-file emission settings computed by the compiler driver.</summary>
public sealed class EmitContext
{
    public required string Namespace { get; init; }
    public required string ModuleClassName { get; init; }
    /// <summary>True when this file holds the program's top-level statements.</summary>
    public bool IsEntry { get; init; }
    public bool EmitLineDirectives { get; init; } = true;
    /// <summary>True when compiling an executable (as opposed to a class library).</summary>
    public bool IsProgram { get; init; }
}

/// <summary>
/// Lowers a bound JS.Net compilation unit to C# source. Roslyn then produces standard IL, PDBs, NativeAOT
/// output, analyzers and IDE support ("Roslyn backend" strategy). <c>#line</c> directives map every
/// statement back to the original <c>.jsn</c> file so errors and breakpoints point at JS.Net code.
/// </summary>
public sealed partial class CSharpEmitter
{
    internal const string Rt = "global::JSNet.Runtime.";
    internal const string ListT = "global::System.Collections.Generic.List";
    internal const string TaskT = "global::System.Threading.Tasks.Task";

    private readonly CompilationUnit _unit;
    private readonly SemanticModel _model;
    private readonly EmitContext _ctx;
    private readonly SourceText _source;
    private CodeWriter _w = new();
    private int _tmp;
    private readonly Stack<HashSet<string>> _locals = new();
    private ClassDeclaration? _class;
    private readonly Stack<string?> _returnTypes = new();
    private bool _inGenerator;

    private CSharpEmitter(CompilationUnit unit, SemanticModel model, EmitContext ctx)
    {
        _unit = unit;
        _model = model;
        _ctx = ctx;
        _source = unit.Source;
        _locals.Push(new HashSet<string>(StringComparer.Ordinal));
    }

    public static string Emit(CompilationUnit unit, SemanticModel model, EmitContext ctx) => new CSharpEmitter(unit, model, ctx).EmitUnit();

    // ----------------------------------------------------------------------------------- unit

    private string EmitUnit()
    {
        _w.WriteLine("// <auto-generated>");
        _w.WriteLine($"//   Generated by the JS.Net compiler from {Path.GetFileName(_source.Path)}.");
        _w.WriteLine("//   JS.Net — dibuat oleh Gravicode Studios dipimpin oleh Kang Fadhil.");
        _w.WriteLine("// </auto-generated>");
        _w.WriteLine("#nullable enable annotations");
        _w.WriteLine("#pragma warning disable CS1998, CS0162, CS0168, CS0219, CS8981, CS0108, CS0114, CS1591, CS8321, CS0649, CS0169, CS0414, CS4014, CS8892");

        foreach (var alias in _unit.Statements.OfType<TypeAliasDeclaration>())
            _w.WriteLine($"global using {CSharpNames.Id(alias.Name)} = {MapType(alias.Type)};");
        foreach (var import in _unit.Statements.OfType<ImportDeclaration>()) EmitImport(import);
        _w.WriteLine($"using {_ctx.Namespace};");

        var functions = _unit.Statements.OfType<FunctionDeclaration>().Where(f => (f.Modifiers & Modifiers.Declare) == 0).ToList();
        var variables = _unit.Statements.OfType<VariableStatement>().ToList();
        var localFunctions = new List<FunctionDeclaration>();
        var moduleFunctions = functions;

        if (_ctx.IsEntry)
        {
            var topVars = new HashSet<string>(variables.SelectMany(v => v.Declarators).SelectMany(d => PatternNames(d.Target)), StringComparer.Ordinal);
            localFunctions = functions.Where(f => !f.IsAi && (f.Modifiers & Modifiers.Export) == 0 && Captures(f, topVars)).ToList();
            moduleFunctions = functions.Except(localFunctions).ToList();
        }

        _w.Directive("#line default");
        _w.Open($"namespace {_ctx.Namespace}");
        foreach (var stmt in _unit.Statements)
        {
            switch (stmt)
            {
                case ClassDeclaration c when (c.Modifiers & Modifiers.Declare) == 0: EmitClass(c); break;
                case InterfaceDeclaration i when (i.Modifiers & Modifiers.Declare) == 0: EmitInterface(i); break;
                case EnumDeclaration e when (e.Modifiers & Modifiers.Declare) == 0: EmitEnum(e); break;
                case PromptDeclaration p: EmitPrompt(p); break;
            }
        }

        var moduleVars = _ctx.IsEntry ? [] : variables;
        if (functions.Count > 0 || variables.Count > 0 || _ctx.IsEntry)
        {
            _w.Directive("#line hidden");
            _w.WriteLine("/// <summary>Top-level functions and variables of this JS.Net module.</summary>");
            _w.Open($"public static partial class {_ctx.ModuleClassName}");
            // Top-level statements become Main inside the namespace, so project types win over same-named BCL types.
            if (_ctx.IsEntry) EmitTopLevelStatements(localFunctions);
            foreach (var v in moduleVars) EmitModuleVariable(v);
            foreach (var f in moduleFunctions) EmitFunction(f, isStatic: true, isLocal: false);
            _w.Close();
        }
        _w.Close();
        _w.Directive("#line default");
        return _w.ToString();
    }

    private static IEnumerable<string> PatternNames(Pattern p) => p switch
    {
        IdentifierPattern i => [i.Name],
        ObjectPattern o => o.Properties.SelectMany(x => PatternNames(x.Value)),
        ArrayPattern a => a.Elements.Where(e => e is not null).SelectMany(e => PatternNames(e!)),
        _ => [],
    };

    private static bool Captures(FunctionDeclaration f, HashSet<string> names) =>
        f.Body is not null && AstWalker.DescendantsAndSelf(f.Body).OfType<IdentifierExpression>().Any(id => names.Contains(id.Name));

    private void EmitImport(ImportDeclaration import)
    {
        switch (import.Kind)
        {
            case ImportKind.Namespace:
                _w.WriteLine($"using {import.Module};");
                break;
            case ImportKind.Static:
                _w.WriteLine($"using static {import.Module};");
                break;
            case ImportKind.Alias:
                _w.WriteLine($"using {CSharpNames.Id(import.Alias!)} = {import.Module};");
                break;
            case ImportKind.Named:
                foreach (var (name, alias) in import.Names)
                    _w.WriteLine($"using {CSharpNames.Id(alias)} = {import.Module}.{name};");
                break;
        }
    }

    private void EmitTopLevelStatements(List<FunctionDeclaration> localFunctions)
    {
        _w.WriteLine($"public static async {TaskT} Main(string[] args)");
        _w.WriteLine("{");
        _w.Indent++;
        DeclareLocal("args");
        _returnTypes.Push(null);
        foreach (var stmt in _unit.Statements)
        {
            if (stmt is FunctionDeclaration or ClassDeclaration or InterfaceDeclaration or EnumDeclaration or ImportDeclaration
                or NamespaceDeclaration or TypeAliasDeclaration or PromptDeclaration) continue;
            EmitStatement(stmt);
        }
        // Like Node.js, the process stays alive until pending timers (setTimeout/setInterval) have run.
        Hidden();
        _w.WriteLine($"await {Rt}EventLoop.drainAsync();");
        foreach (var f in localFunctions) EmitFunction(f, isStatic: false, isLocal: true);
        _returnTypes.Pop();
        _w.Indent--;
        _w.WriteLine("}");
    }

    // -------------------------------------------------------------------------- line mapping

    private void Line(Node node)
    {
        if (!_ctx.EmitLineDirectives || node.Span.Length == 0 && node.Span.Start == 0 && node is not CompilationUnit) return;
        var (l1, c1) = _source.GetLineColumn(node.Span.Start);
        var (l2, c2) = _source.GetLineColumn(Math.Max(node.Span.Start, node.Span.End));
        if (l2 < l1 || (l2 == l1 && c2 <= c1)) { l2 = l1; c2 = c1 + 1; }
        _w.Directive($"#line ({l1}, {c1}) - ({l2}, {c2}) {_w.IndentColumns + 1} \"{_source.Path}\"");
    }

    private void Hidden()
    {
        if (_ctx.EmitLineDirectives) _w.Directive("#line hidden");
    }

    // ------------------------------------------------------------------------------- helpers

    private string MapType(TypeNode? type) => TypeMapper.Map(type);

    private string Tmp(string hint = "t") => $"__{hint}{++_tmp}";

    private void PushLocals() => _locals.Push(new HashSet<string>(StringComparer.Ordinal));
    private void PopLocals() => _locals.Pop();
    private void DeclareLocal(string name) => _locals.Peek().Add(name);
    private bool IsLocal(string name) => _locals.Any(s => s.Contains(name));

    private string? TypeOf(Node n) => _model.GetInferredType(n);

    private static bool IsValueTypeName(string t) => t is "int" or "long" or "double" or "float" or "decimal" or "bool" or "char" or "byte"
        or "short" or "uint" or "ulong" or "ushort" or "sbyte" || t.StartsWith('(');

    private bool IsValueType(string t) => IsValueTypeName(t) || _model.Symbols.Enums.Contains(t)
        || (_model.Symbols.Classes.TryGetValue(t, out var c) && c.Declaration.Kind == ClassKind.Struct);

    private static string Accessibility(Modifiers m, string @default = "public")
    {
        if ((m & Modifiers.Private) != 0) return "private";
        if ((m & Modifiers.Protected) != 0) return "protected";
        if ((m & Modifiers.Internal) != 0) return "internal";
        if ((m & Modifiers.Public) != 0) return "public";
        return @default;
    }

    private string Attributes(List<AttributeNode> attrs, string? target = null)
    {
        if (attrs.Count == 0) return string.Empty;
        var sb = new StringBuilder();
        foreach (var a in attrs)
        {
            sb.Append('[');
            if (a.Target is not null) sb.Append(a.Target).Append(": ");
            else if (target is not null) sb.Append(target).Append(": ");
            sb.Append(a.Name);
            if (a.Args.Count > 0)
            {
                sb.Append('(');
                var parts = new List<string>();
                foreach (var arg in a.Args)
                {
                    if (arg is ObjectExpression obj && ReferenceEquals(arg, a.Args[^1]))
                        parts.AddRange(obj.Properties.Select(p => $"{CSharpNames.Id(p.Key)} = {Expr(p.Value)}"));
                    else parts.Add(Expr(arg));
                }
                sb.Append(string.Join(", ", parts)).Append(')');
            }
            sb.Append("] ");
        }
        return sb.ToString();
    }

    private void WriteAttributes(List<AttributeNode> attrs)
    {
        foreach (var a in attrs) _w.WriteLine(Attributes([a]).TrimEnd());
    }

    private string TypeParameters(List<TypeParameter> tps) =>
        tps.Count == 0 ? string.Empty : "<" + string.Join(", ", tps.Select(t => CSharpNames.Id(t.Name))) + ">";

    private string Constraints(List<TypeParameter> tps)
    {
        var parts = tps.Where(t => t.Constraint is not null).Select(t =>
        {
            string c = MapType(t.Constraint);
            c = c switch { "object" => "class", "dynamic" => "class", _ => c };
            return $" where {CSharpNames.Id(t.Name)} : {c}";
        });
        return string.Concat(parts);
    }

    private static bool IsConstant(Expression e) => e switch
    {
        LiteralExpression => true,
        UnaryExpression { Operator: "-" or "+", Operand: LiteralExpression { Kind: LiteralKind.Number } } => true,
        MemberExpression { Target: IdentifierExpression or MemberExpression } m => char.IsUpper(m.Name[0]) || m.Name is "PI" or "E",
        _ => false,
    };

    /// <summary>Builds a C# parameter list. Non-constant defaults and destructured parameters add statements to <paramref name="prologue"/>.</summary>
    private string Parameters(List<Parameter> parameters, List<string> prologue, bool allowDefaults = true)
    {
        var parts = new List<string>();
        foreach (var p in parameters)
        {
            string name = p.Pattern is not null ? $"__p{parts.Count}" : CSharpNames.Id(p.Name);
            string type = p.Type is not null ? MapType(p.Type) : TypeOf(p) ?? "dynamic";
            var sb = new StringBuilder();
            sb.Append(Attributes(p.Attributes));
            if (p.Rest)
            {
                if (p.Type is null) type = "object[]";
                else if (!type.EndsWith("[]", StringComparison.Ordinal) && !type.StartsWith(ListT, StringComparison.Ordinal)) type += "[]";
                sb.Append("params ").Append(type).Append(' ').Append(name);
            }
            else
            {
                if (p.Optional && p.Default is null && IsValueType(type)) type += "?";
                sb.Append(type).Append(' ').Append(name);
                if (p.Default is not null && allowDefaults)
                {
                    if (IsConstant(p.Default)) sb.Append(" = ").Append(Expr(p.Default, type));
                    else
                    {
                        if (IsValueType(type)) { sb.Insert(sb.Length - name.Length - 1, "?"); }
                        sb.Append(" = default");
                        prologue.Add($"{name} ??= {Expr(p.Default, type)};");
                    }
                }
                else if (p.Optional && allowDefaults) sb.Append(" = default");
            }
            if (p.Pattern is not null) prologue.Add(DestructureCode(p.Pattern, name, isDeclaration: true));
            parts.Add(sb.ToString());
        }
        return string.Join(", ", parts);
    }

    private void DeclareParameters(List<Parameter> parameters)
    {
        foreach (var p in parameters)
        {
            if (p.Pattern is not null) foreach (var n in PatternNames(p.Pattern)) DeclareLocal(n);
            else DeclareLocal(p.Name);
        }
    }

    private string ReturnType(TypeNode? annotated, Node node, bool isAsync, bool isGenerator)
    {
        if (annotated is not null)
        {
            string t = MapType(annotated);
            if (isGenerator)
            {
                if (!t.Contains("IEnumerable", StringComparison.Ordinal) && !t.Contains("IAsyncEnumerable", StringComparison.Ordinal))
                    t = isAsync ? $"global::System.Collections.Generic.IAsyncEnumerable<{t}>" : $"global::System.Collections.Generic.IEnumerable<{t}>";
                return t;
            }
            if (isAsync && t != "void" && !t.StartsWith(TaskT, StringComparison.Ordinal) && !t.StartsWith("global::System.Threading.Tasks.ValueTask", StringComparison.Ordinal)
                && !t.StartsWith("Task", StringComparison.Ordinal) && !t.StartsWith("ValueTask", StringComparison.Ordinal))
                t = $"{TaskT}<{t}>";
            return t;
        }
        return TypeOf(node) ?? (isAsync ? TaskT : "void");
    }

    /// <summary>The type a <c>return</c> expression converts to (Task/IEnumerable unwrapped).</summary>
    private static string? ReturnTargetOf(string returnType, bool isAsync)
    {
        if (returnType is "void" or "dynamic") return null;
        if (isAsync) return TypeMapper.UnwrapTask(returnType);
        return returnType;
    }

    // ------------------------------------------------------------------------------- functions

    private void EmitFunction(FunctionDeclaration f, bool isStatic, bool isLocal)
    {
        if (f.IsAi)
        {
            EmitAiFunction(f, isLocal);
            return;
        }
        if (f.Body is null) return; // overload signature / ambient declaration

        Line(f);
        WriteAttributes(f.Attributes);
        string ret = ReturnType(f.ReturnType, f, f.IsAsync, f.IsGenerator);
        PushLocals();
        DeclareParameters(f.Parameters);
        var prologue = new List<string>();
        string ps = Parameters(f.Parameters, prologue);
        var sb = new StringBuilder();
        if (!isLocal) sb.Append(Accessibility(f.Modifiers)).Append(' ');
        if (isStatic) sb.Append("static ");
        if (f.IsAsync) sb.Append("async ");
        // A top-level `function main()` in a program without top-level statements becomes the CLR entry point
        // (needed for [STAThread] desktop apps).
        string fname = !isLocal && f.Name == "main" && _ctx.IsProgram && !_ctx.IsEntry ? "Main" : CSharpNames.Id(f.Name);
        sb.Append(ret).Append(' ').Append(fname).Append(TypeParameters(f.TypeParameters))
          .Append('(').Append(ps).Append(')').Append(Constraints(f.TypeParameters));
        EmitBody(f.Body, sb.ToString(), prologue, ReturnTargetOf(ret, f.IsAsync), f.IsGenerator);
        PopLocals();
    }

    private void EmitBody(BlockStatement body, string header, List<string> prologue, string? returnTarget, bool isGenerator, string? ctorInitializer = null)
    {
        _w.WriteLine(header);
        if (ctorInitializer is not null) _w.WriteLine("    " + ctorInitializer);
        _w.WriteLine("{");
        _w.Indent++;
        foreach (var p in prologue) _w.WriteLine(p);
        _returnTypes.Push(returnTarget);
        bool savedGen = _inGenerator;
        _inGenerator = isGenerator;
        foreach (var s in body.Statements) EmitStatement(s);
        _inGenerator = savedGen;
        _returnTypes.Pop();
        _w.Indent--;
        _w.WriteLine("}");
    }

    private void EmitAiFunction(FunctionDeclaration f, bool isLocal)
    {
        Line(f);
        WriteAttributes(f.Attributes);
        string resultType = "string";
        if (f.ReturnType is not null)
        {
            string mapped = MapType(f.ReturnType);
            resultType = TypeMapper.UnwrapTask(mapped) ?? (mapped == TaskT ? "string" : mapped);
        }
        PushLocals();
        DeclareParameters(f.Parameters);
        var prologue = new List<string>();
        string ps = Parameters(f.Parameters, prologue);
        Expression? template = f.Body?.Statements.FirstOrDefault() switch
        {
            ExpressionStatement { Expression: LiteralExpression { Kind: LiteralKind.String } or TemplateExpression } es => es.Expression,
            ReturnStatement { Value: { } v } => v,
            _ => null,
        };
        string args = f.Parameters.Count == 0
            ? "null"
            : "new global::System.Collections.Generic.Dictionary<string, object?> { " +
              string.Join(", ", f.Parameters.Select(p => $"[{CSharpNames.StringLiteral(p.Name)}] = {CSharpNames.Id(p.Name)}")) + " }";
        string access = isLocal ? string.Empty : Accessibility(f.Modifiers) + " static ";
        _w.Open($"{access}async {TaskT}<{resultType}> {CSharpNames.Id(f.Name)}({ps})");
        foreach (var p in prologue) _w.WriteLine(p);
        string tpl = template is null ? "null" : Expr(template);
        _w.WriteLine($"return await global::JSNet.AI.AiRuntime.invokeAsync<{resultType}>({CSharpNames.StringLiteral(f.Name)}, {tpl}, {args});");
        _w.Close();
        PopLocals();
    }

    private void EmitModuleVariable(VariableStatement v)
    {
        foreach (var d in v.Declarators)
        {
            if (d.Target is not IdentifierPattern ip) continue;
            Line(d);
            string type = d.Type is not null ? MapType(d.Type) : v.Kind == VariableKind.Dynamic ? "dynamic" : TypeOf(d) ?? "dynamic";
            string access = Accessibility(v.Modifiers);
            string mods = v.Kind == VariableKind.Const ? "static readonly" : "static";
            string init = d.Init is not null ? " = " + Expr(d.Init, type) : string.Empty;
            _w.WriteLine($"{access} {mods} {type} {CSharpNames.Id(ip.Name)}{init};");
        }
    }

    // --------------------------------------------------------------------------------- classes

    private void EmitClass(ClassDeclaration c)
    {
        var saved = _class;
        _class = c;
        Line(c);
        WriteAttributes(c.Attributes);
        var header = new StringBuilder();
        header.Append(Accessibility(c.Modifiers & ~Modifiers.Private, "public")).Append(' ');
        if ((c.Modifiers & Modifiers.Abstract) != 0) header.Append("abstract ");
        if ((c.Modifiers & Modifiers.Sealed) != 0) header.Append("sealed ");
        if ((c.Modifiers & Modifiers.Static) != 0) header.Append("static ");
        header.Append("partial ");
        header.Append(c.Kind switch { ClassKind.Struct => "struct", ClassKind.Record => "record class", _ => "class" });
        header.Append(' ').Append(CSharpNames.Id(c.Name)).Append(TypeParameters(c.TypeParameters));
        var bases = new List<string>();
        if (c.Extends is not null) bases.Add(MapType(c.Extends));
        bases.AddRange(c.Implements.Select(MapType));
        if (bases.Count > 0) header.Append(" : ").Append(string.Join(", ", bases));
        header.Append(Constraints(c.TypeParameters));
        _w.Open(header.ToString());

        bool extended = _model.IsExtended(c.Name);
        var emittedAccessors = new HashSet<string>(StringComparer.Ordinal);
        foreach (var m in c.Members)
        {
            if ((m.Modifiers & Modifiers.Declare) != 0) continue;
            switch (m.Kind)
            {
                case MemberKind.Field: EmitField(m); break;
                case MemberKind.Constructor: EmitConstructor(c, m); break;
                case MemberKind.Method: EmitMethod(c, m, extended); break;
                case MemberKind.Getter or MemberKind.Setter:
                    if (emittedAccessors.Add(m.Name)) EmitAccessorProperty(c, m.Name, extended);
                    break;
            }
        }

        if (c.Members.Any(m => m.Kind == MemberKind.Method && m.Name == "toString" && m.Parameters.Count == 0 && !m.IsStatic)
            && !c.Members.Any(m => m.Name == "ToString"))
        {
            Hidden();
            _w.WriteLine("public override string ToString() => toString()?.ToString() ?? string.Empty;");
        }
        _w.Close();
        _class = saved;
    }

    private void EmitField(ClassMember m)
    {
        Line(m);
        WriteAttributes(m.Attributes);
        string type = m.Type is not null ? MapType(m.Type) : TypeOf(m) ?? "dynamic";
        if (m.Optional && IsValueType(type)) type += "?";
        string name = CSharpNames.Id(m.Name);
        string init = m.Init is not null ? " = " + Expr(m.Init, type) + ";" : string.Empty;
        bool isPrivate = (m.Modifiers & (Modifiers.Private | Modifiers.Protected)) != 0 || m.Name.StartsWith('#');
        bool isReadonly = (m.Modifiers & Modifiers.Readonly) != 0;
        string stat = m.IsStatic ? "static " : string.Empty;
        if (isPrivate)
        {
            string access = m.Name.StartsWith('#') ? "private" : Accessibility(m.Modifiers);
            _w.WriteLine($"{access} {stat}{(isReadonly ? "readonly " : "")}{type} {name}{(init.Length > 0 ? init : ";")}");
        }
        else
        {
            string accessors = isReadonly ? "{ get; }" : "{ get; set; }";
            _w.WriteLine($"{Accessibility(m.Modifiers)} {stat}{(m.Modifiers.HasFlag(Modifiers.Override) ? "override " : "")}{type} {name} {accessors}{init}");
        }
    }

    private void EmitConstructor(ClassDeclaration c, ClassMember m)
    {
        // Parameter properties become members first.
        foreach (var p in m.Parameters.Where(p => p.PropertyModifiers != Modifiers.None))
        {
            string type = p.Type is not null ? MapType(p.Type) : "dynamic";
            bool isPrivate = (p.PropertyModifiers & (Modifiers.Private | Modifiers.Protected)) != 0;
            bool ro = (p.PropertyModifiers & Modifiers.Readonly) != 0;
            Line(p);
            if (isPrivate) _w.WriteLine($"{Accessibility(p.PropertyModifiers)} {(ro ? "readonly " : "")}{type} {CSharpNames.Id(p.Name)};");
            else _w.WriteLine($"{Accessibility(p.PropertyModifiers)} {type} {CSharpNames.Id(p.Name)} {(ro ? "{ get; }" : "{ get; set; }")}");
        }

        if (m.Body is null) return;
        Line(m);
        WriteAttributes(m.Attributes);
        PushLocals();
        DeclareParameters(m.Parameters);
        var prologue = new List<string>();
        string ps = Parameters(m.Parameters, prologue);
        foreach (var p in m.Parameters.Where(p => p.PropertyModifiers != Modifiers.None))
            prologue.Insert(0, $"this.{CSharpNames.Id(p.Name)} = {CSharpNames.Id(p.Name)};");

        string? init = null;
        var statements = m.Body.Statements;
        var body = m.Body;
        if (statements.Count > 0 && statements[0] is ExpressionStatement { Expression: CallExpression { Callee: SuperExpression } superCall })
        {
            init = $": base({Arguments(superCall.Args)})";
            body = new BlockStatement(statements.Skip(1).ToList()) { Span = m.Body.Span };
        }
        string access = Accessibility(m.Modifiers);
        string stat = m.IsStatic ? "static " : access + " ";
        EmitBody(body, $"{stat}{CSharpNames.Id(c.Name)}({ps})", prologue, null, false, init);
        PopLocals();
    }

    private string MethodModifiers(ClassDeclaration c, ClassMember m, bool extended)
    {
        var sb = new StringBuilder();
        sb.Append(Accessibility(m.Modifiers)).Append(' ');
        if (m.IsStatic) sb.Append("static ");
        bool isAbstract = (m.Modifiers & Modifiers.Abstract) != 0 || (m.Body is null && (c.Modifiers & Modifiers.Abstract) != 0);
        if (isAbstract) sb.Append("abstract ");
        else if ((m.Modifiers & Modifiers.Override) != 0 || (!m.IsStatic && _model.OverridesProjectMethod(c, m))) sb.Append("override ");
        else if ((m.Modifiers & Modifiers.Virtual) != 0) sb.Append("virtual ");
        else if (extended && !m.IsStatic && (m.Modifiers & Modifiers.Private) == 0 && c.Kind != ClassKind.Struct) sb.Append("virtual ");
        if ((m.Modifiers & Modifiers.Sealed) != 0) sb.Append("sealed ");
        if (m.IsAsync && !isAbstract) sb.Append("async ");
        return sb.ToString();
    }

    private void EmitMethod(ClassDeclaration c, ClassMember m, bool extended)
    {
        bool isAbstract = (m.Modifiers & Modifiers.Abstract) != 0 || (m.Body is null && (c.Modifiers & Modifiers.Abstract) != 0);
        if (m.Body is null && !isAbstract) return;
        Line(m);
        WriteAttributes(m.Attributes);
        string ret = ReturnType(m.Type, m, m.IsAsync, m.IsGenerator);
        PushLocals();
        DeclareParameters(m.Parameters);
        var prologue = new List<string>();
        string ps = Parameters(m.Parameters, prologue);
        string header = $"{MethodModifiers(c, m, extended)}{ret} {CSharpNames.Id(m.Name)}{TypeParameters(m.TypeParameters)}({ps}){Constraints(m.TypeParameters)}";
        if (isAbstract) _w.WriteLine(header + ";");
        else EmitBody(m.Body!, header, prologue, ReturnTargetOf(ret, m.IsAsync), m.IsGenerator);
        PopLocals();
    }

    private void EmitAccessorProperty(ClassDeclaration c, string name, bool extended)
    {
        var getter = c.Members.FirstOrDefault(x => x.Kind == MemberKind.Getter && x.Name == name);
        var setter = c.Members.FirstOrDefault(x => x.Kind == MemberKind.Setter && x.Name == name);
        var first = getter ?? setter!;
        string type = getter?.Type is not null ? MapType(getter.Type)
            : setter?.Parameters.FirstOrDefault()?.Type is { } st ? MapType(st)
            : getter is not null ? TypeOf(getter) ?? "dynamic" : "dynamic";
        Line(first);
        WriteAttributes(first.Attributes);
        _w.WriteLine($"{MethodModifiers(c, first, extended).Replace("async ", "", StringComparison.Ordinal)}{type} {CSharpNames.Id(name)}");
        _w.WriteLine("{");
        _w.Indent++;
        if (getter is not null)
        {
            if (getter.Body is null) _w.WriteLine("get;");
            else
            {
                PushLocals();
                EmitBody(getter.Body, "get", [], type, false);
                PopLocals();
            }
        }
        if (setter is not null)
        {
            if (setter.Body is null) _w.WriteLine("set;");
            else
            {
                PushLocals();
                var prologue = new List<string>();
                string pname = setter.Parameters.FirstOrDefault()?.Name ?? "value";
                DeclareLocal(pname);
                if (pname != "value") prologue.Add($"var {CSharpNames.Id(pname)} = value;");
                EmitBody(setter.Body, "set", prologue, null, false);
                PopLocals();
            }
        }
        _w.Indent--;
        _w.WriteLine("}");
    }

    private void EmitInterface(InterfaceDeclaration i)
    {
        Line(i);
        string bases = i.Extends.Count > 0 ? " : " + string.Join(", ", i.Extends.Select(MapType)) : string.Empty;
        _w.Open($"{Accessibility(i.Modifiers & ~Modifiers.Private)} partial interface {CSharpNames.Id(i.Name)}{TypeParameters(i.TypeParameters)}{bases}{Constraints(i.TypeParameters)}");
        var accessors = new HashSet<string>(StringComparer.Ordinal);
        foreach (var m in i.Members)
        {
            Line(m);
            switch (m.Kind)
            {
                case MemberKind.Field:
                {
                    string type = MapType(m.Type);
                    if (m.Optional && IsValueType(type)) type += "?";
                    bool ro = (m.Modifiers & Modifiers.Readonly) != 0;
                    _w.WriteLine($"{type} {CSharpNames.Id(m.Name)} {(ro ? "{ get; }" : "{ get; set; }")}");
                    break;
                }
                case MemberKind.Getter or MemberKind.Setter:
                    if (!accessors.Add(m.Name)) break;
                    bool hasSet = i.Members.Any(x => x.Kind == MemberKind.Setter && x.Name == m.Name);
                    bool hasGet = i.Members.Any(x => x.Kind == MemberKind.Getter && x.Name == m.Name);
                    string ptype = m.Kind == MemberKind.Getter ? MapType(m.Type) : MapType(m.Parameters.FirstOrDefault()?.Type);
                    _w.WriteLine($"{ptype} {CSharpNames.Id(m.Name)} {{ {(hasGet ? "get; " : "")}{(hasSet ? "set; " : "")}}}");
                    break;
                default:
                {
                    var prologue = new List<string>();
                    string ret = m.Type is null ? "void" : ReturnType(m.Type, m, m.IsAsync, m.IsGenerator);
                    _w.WriteLine($"{ret} {CSharpNames.Id(m.Name)}{TypeParameters(m.TypeParameters)}({Parameters(m.Parameters, prologue)}){Constraints(m.TypeParameters)};");
                    break;
                }
            }
        }
        _w.Close();

        // Data-only interfaces get a hidden implementation so object literals can target them.
        if (DataInterfaceMembers(i.Name) is { } members && i.TypeParameters.Count == 0)
        {
            Hidden();
            _w.WriteLine("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
            _w.Open($"public sealed class {CSharpNames.Id(i.Name)}__Data : {CSharpNames.Id(i.Name)}");
            foreach (var m in members)
            {
                string type = MapType(m.Type);
                if (m.Optional && IsValueType(type)) type += "?";
                _w.WriteLine($"public {type} {CSharpNames.Id(m.Name)} {{ get; set; }}");
            }
            _w.Close();
        }
    }

    /// <summary>All members of a project interface (including inherited ones) when it only declares properties.</summary>
    private List<ClassMember>? DataInterfaceMembers(string name)
    {
        var result = new List<ClassMember>();
        var visited = new HashSet<string>(StringComparer.Ordinal);
        bool Walk(string n)
        {
            if (!visited.Add(n)) return true;
            if (!_model.Symbols.Interfaces.TryGetValue(n, out var decl)) return false;
            if (decl.Members.Any(m => m.Kind != MemberKind.Field)) return false;
            result.AddRange(decl.Members.Where(m => result.All(r => r.Name != m.Name)));
            foreach (var b in decl.Extends)
                if (b is not NamedType nt || !Walk(nt.Name)) return false;
            return true;
        }
        return Walk(name) && result.Count > 0 ? result : null;
    }

    private void EmitEnum(EnumDeclaration e)
    {
        Line(e);
        bool stringEnum = e.Members.Any(m => m.Value is LiteralExpression { Kind: LiteralKind.String } or TemplateExpression);
        if (stringEnum)
        {
            _w.Open($"{Accessibility(e.Modifiers)} static partial class {CSharpNames.Id(e.Name)}");
            foreach (var m in e.Members)
                _w.WriteLine($"public const string {CSharpNames.Id(m.Name)} = {(m.Value is null ? CSharpNames.StringLiteral(m.Name) : Expr(m.Value))};");
            _w.Close();
            return;
        }
        _w.Open($"{Accessibility(e.Modifiers)} enum {CSharpNames.Id(e.Name)}");
        foreach (var m in e.Members)
            _w.WriteLine(m.Value is null ? $"{CSharpNames.Id(m.Name)}," : $"{CSharpNames.Id(m.Name)} = {Expr(m.Value)},");
        _w.Close();
    }

    private void EmitPrompt(PromptDeclaration p)
    {
        Line(p);
        string output = p.Output is null ? "string" : MapType(p.Output);
        _w.Open($"{Accessibility(p.Modifiers)} sealed partial class {CSharpNames.Id(p.Name)} : global::JSNet.AI.Prompt<{output}>");
        PushLocals();
        foreach (var f in p.Fields)
        {
            _w.WriteLine($"public {MapType(f.Type)} {CSharpNames.Id(f.Name)} {{ get; set; }}");
            DeclareLocal(f.Name);
        }
        string template = p.Template is null ? "string.Empty" : Expr(p.Template);
        _w.WriteLine($"public override string render() => {template};");
        string ps = string.Join(", ", p.Fields.Select(f => $"{MapType(f.Type)} {CSharpNames.Id(f.Name)}"));
        string assigns = string.Join(", ", p.Fields.Select(f => $"{CSharpNames.Id(f.Name)} = {CSharpNames.Id(f.Name)}"));
        _w.WriteLine($"public static {TaskT}<{output}> run({ps}) => new {CSharpNames.Id(p.Name)} {{ {assigns} }}.invokeAsync();");
        PopLocals();
        _w.Close();
    }
