/// <summary>MLX90640 register model: 16-bit addresses, big-endian words, EEPROM + RAM + status/control.</summary>
public class SimMlx90640 : I2cDevice
{
    public int[] Eeprom = new int[832];
    public int[] Ram = new int[832];
    public int Status = 0x0008; // new data, subpage 0
    public int Control = 0x1901; // chess, 18-bit, 2 Hz (power-on default)
    public int Pointer;
    public int LastStatusWrite = -1;

    public SimMlx90640()
    {
        Address = 0x33;
    }

    public override void Write(byte[] data)
    {
        Pointer = (data[0] << 8) | data[1];
        if (data.Length >= 4)
        {
            int v = (data[2] << 8) | data[3];
            if (Pointer == 0x8000)
            {
                LastStatusWrite = v;
            }
            else if (Pointer == 0x800D)
            {
                Control = v;
            }
        }
    }

    private int Word(int a)
    {
        if (a >= 0x2400 && a < 0x2400 + 832)
        {
            return Eeprom[a - 0x2400];
        }
        if (a >= 0x0400 && a < 0x0400 + 832)
        {
            return Ram[a - 0x0400];
        }
        if (a == 0x8000)
        {
            return Status;
        }
        if (a == 0x800D)
        {
            return Control;
        }
        return 0;
    }

    public override byte[] Read(int length)
    {
        byte[] r = new byte[length];
        for (int i = 0; i + 1 < length; i += 2)
        {
            int w = Word(Pointer + i / 2);
            r[i] = (byte)(w >> 8);
            r[i + 1] = (byte)w;
        }
        return r;
    }

    public static int[] Words(string hex)
    {
        int[] r = new int[hex.Length / 4];
        for (int i = 0; i < r.Length; i++)
        {
            int v = 0;
            for (int k = 0; k < 4; k++)
            {
                char c = hex[i * 4 + k];
                v = v * 16 + (c <= '9' ? c - '0' : c - 'A' + 10);
            }
            r[i] = v;
        }
        return r;
    }
}

