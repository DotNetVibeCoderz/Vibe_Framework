    public static void Run()
    {
        SimMlx90640 sim = new SimMlx90640();
        sim.Eeprom = SimMlx90640.Words(Eeprom);
        int[] ram = SimMlx90640.Words(Ram);
        sim.Ram = ram;
        Mlx90640 cam = new Mlx90640(sim);
        cam.WordsPerRead = 100;
        Check.True("mlx90640 begin", cam.Begin());
        Mlx90640Parameters p = cam.Params;
        // Datasheet example: Kvdd = -3168, Vdd25 = -13056, KtPTAT = 42.25, alphaPTAT = 9.
        Check.Equal("mlx90640 kvdd", -3168, p.KVdd);
        Check.Equal("mlx90640 vdd25", -13056, p.Vdd25);
        Check.Near("mlx90640 ktptat", 42.25, p.KtPtat, 1e-12);
        Check.Near("mlx90640 kvptat", 22.0 / 4096.0, p.KvPtat, 1e-12);
        Check.Near("mlx90640 alphaptat", 9.0, p.AlphaPtat, 1e-12);
        Check.Equal("mlx90640 resolution ee", 2, p.ResolutionEE);
        Check.Equal("mlx90640 ct2", 100, p.Ct[2]);
        Check.Equal("mlx90640 ct3", 320, p.Ct[3]);
        Check.Equal("mlx90640 offset[0]", -82, p.Offset[0]);
        Check.Equal("mlx90640 alpha[0]", 22559, p.Alpha[0]);
        Check.Equal("mlx90640 kta[0]", 75, p.Kta[0]);
        Check.Equal("mlx90640 kv[0]", 80, p.Kv[0]);
        Check.Equal("mlx90640 alpha scale", 13, p.AlphaScale);
        Check.Equal("mlx90640 kta scale", 14, p.KtaScale);
        Check.Equal("mlx90640 kv scale", 7, p.KvScale);
        Check.Equal("mlx90640 broken pixel", 6, p.BrokenPixels.Count == 1 ? p.BrokenPixels[0] : -1);
        Check.Equal("mlx90640 outlier pixel", 5, p.OutlierPixels.Count == 1 ? p.OutlierPixels[0] : -1);

        int[]? f0 = cam.ReadFrame();
        Check.True("mlx90640 frame", f0 != null && f0.Length == 834);
        if (f0 == null)
        {
            return;
        }
        Check.Equal("mlx90640 cleared new-data", 0x0030, sim.LastStatusWrite);
        Check.Equal("mlx90640 frame control", 0x1901, f0[832]);
        Check.Near("mlx90640 vdd (datasheet 3.319)", 3.3186237373737373, cam.GetVdd(f0), 1e-9);
        Check.Near("mlx90640 ta (datasheet 39.184)", 39.18442378914584, cam.GetTa(f0), 1e-9);
        double[] img = new double[768];
        cam.CalculateTo(f0, 0.95, 30.0, img);
        sim.Status = 0x0009; // subpage 1
        int[]? f1 = cam.ReadFrame();
        if (f1 != null)
        {
            Check.Equal("mlx90640 subpage 1", 1, f1[833]);
            cam.CalculateTo(f1, 0.95, 30.0, img);
        }
        Check.Near("mlx90640 to[0]", 49.03209421536474, img[0], 1e-6);
        Check.Near("mlx90640 to[1]", 47.250541335896116, img[1], 1e-6);
        Check.Near("mlx90640 to[5]", 45.638856123834216, img[5], 1e-6);
        Check.Near("mlx90640 to[6]", 40.31733971304095, img[6], 1e-6);
        Check.Near("mlx90640 to[33]", 50.00386487101059, img[33], 1e-6);
        Check.Near("mlx90640 to[100]", 50.0901094980652, img[100], 1e-6);
        Check.Near("mlx90640 to[383]", 48.51065432679587, img[383], 1e-6);
        Check.Near("mlx90640 to[500]", 41.9838775850742, img[500], 1e-6);
        Check.Near("mlx90640 to[767]", 55.107220981422586, img[767], 1e-6);

        cam.SetRefreshRate(4); // 8 Hz
        Check.Equal("mlx90640 refresh rate", 0x1A01, sim.Control);
        cam.SetResolution(3);
        Check.Equal("mlx90640 resolution", 0x1E01, sim.Control);
        cam.SetChessMode(false);
        Check.Equal("mlx90640 interleaved", 0x0E01, sim.Control);
    }
